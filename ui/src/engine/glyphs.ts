/** What a tag is drawn with: the symbol picked for it, or one that suits its name. */
export function tagGlyph(tag: string, picked: Record<string, string>): IconName {
  const chosen = picked[tag];
  return (chosen && GLYPH_CHOICES[chosen]) || tagAutomatic(tag);
}

export function tagAutomatic(tag: string): IconName {
  return TAG_AUTOMATIC[tag.trim().toLowerCase()] ?? 'sell';
}
