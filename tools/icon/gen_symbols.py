"""Generates android/app/.../ui/icons/PassIcons.kt from Material Symbols (Apache 2.0).

Rounded, weight 300: a touch lighter than the default, which sits better beside Manrope.
Names ending in `!` also get a filled twin, for the selected state of a tab.
Run from the repository root; downloaded SVGs are cached in target/symbols.
"""
