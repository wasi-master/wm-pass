// Turns the guide in help/ into what the other apps read:
//
// - data/help/help.json for the phone, with every topic as the phone shows it and the text already
//   split into blocks, so the phone never parses anything;
// - docs/src/content/docs/guide/**, the same guide as pages on the docs site.
//
// Both outputs are committed. CI runs this and fails if they differ from what is checked in.
// Run with: npm run help

import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const help = await import(join(root, 'help/index.ts'));
const { PAGES, GROUPS, ancestors } = await import(join(root, 'ui/src/settings/pages.ts'));
const glyphs = (await import(join(root, 'ui/src/icons/outlined.ts'))).default;

const problems = help.validate();
if (problems.length) {
  console.error(`The guide has ${problems.length} problem${problems.length === 1 ? '' : 's'}:\n  ${problems.join('\n  ')}`);
  // HELP_DRAFT=1 writes the files anyway, for working on the apps while topics are half written.
  if (!process.env.HELP_DRAFT) process.exit(1);
}

/** @type {readonly import('../help/schema.ts').Topic[]} */
const TOPICS = help.TOPICS;
const byId = new Map(TOPICS.map((t) => [t.id, t]));

// The shortcut each action starts with, read from the app's own table rather than repeated here.
const prefsSource = readFileSync(join(root, 'ui/src/engine/prefs.svelte.ts'), 'utf8');
const shortcutBlock = prefsSource.slice(prefsSource.indexOf('DEFAULT_SHORTCUTS'), prefsSource.indexOf('};', prefsSource.indexOf('DEFAULT_SHORTCUTS')));
const SHORTCUTS = Object.fromEntries([...shortcutBlock.matchAll(/^\s+([a-z_]+): '([^']*)'/gm)].map((m) => [m[1], m[2]]));

function write(path, text) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}

// ---- the phone ----

function forPhone() {
  const shown = TOPICS.filter((t) => help.availableOn(t, 'android')).map((t) => help.resolve(t, 'android'));
  const titleOf = (id) => {
    const t = byId.get(id);
    return t ? help.resolve(t, 'android').title : id;
  };
  // A link to a topic the phone does not have would lead nowhere there, so it becomes its words.
  const onPhone = (id) => byId.has(id) && help.availableOn(byId.get(id), 'android');
  const settle = (runs) => runs.map((r) => (r.t === 'link' && !onPhone(r.id) ? { t: 'text', s: r.s ?? titleOf(r.id) } : r));
  const text = (rich) =>
    rich === undefined ? undefined : help.blocks(rich).map((b) => (b.t === 'p' ? { t: 'p', runs: settle(b.runs) } : { t: 'ul', items: b.items.map(settle) }));
  const topics = shown.map((t) => ({
    id: t.id,
    kind: t.kind,
    title: t.title,
    page: t.page,
    pref: t.pref,
    what: text(t.what),
    why: text(t.why),
    how: text(t.how),
    when: text(t.when),
    effects: t.effects?.map((e) => ({ value: e.value, label: e.label, text: text(e.text) })),
    caveats: text(t.caveats),
    figure: t.figure,
    preview: t.preview,
    tour: t.tour,
    related: t.related?.filter((id) => byId.has(id) && help.availableOn(byId.get(id), 'android')),
    docs: t.docs,
    words: t.words,
    // What the settings kit's own "?" shows if the guide's sheet is not there.
    plain: help.plain(t.what, titleOf),
  }));
  const tours = help.toursFor('android').map((tour) => ({ ...tour, intro: text(tour.intro), steps: tour.steps.map((s) => ({ ...s, body: text(s.body) })) }));
  return { format: 'wmpass-help', version: 1, shortcuts: SHORTCUTS, topics, tours, figures: help.FIGURES };
}

// JSON.stringify drops undefined fields, so the file only carries what each topic has.
write(join(root, 'data/help/help.json'), `${JSON.stringify(forPhone(), null, 1)}\n`);

// ---- the docs site ----

const OUT = join(root, 'docs/src/content/docs/guide');
const HEADER = '<!-- Generated by scripts/build-help.mjs from help/. Do not edit. -->';

/** Where each topic is written, so links can find it. */
const homeOf = new Map();
const settingsPages = PAGES.filter((p) => p.id !== 'guide');
for (const t of TOPICS) {
  if (t.kind === 'screen') homeOf.set(t.id, '/guide/screens/');
  else if ((t.kind === 'feature' || t.kind === 'concept') && !t.page) homeOf.set(t.id, '/guide/how-it-works/');
  else if (t.page) homeOf.set(t.id, `/guide/settings/${t.page}/`);
}

const anchor = (id) => id.replace(/[^a-z0-9]+/gi, '-').toLowerCase();
const href = (id) => (homeOf.has(id) ? `${homeOf.get(id)}${byId.get(id)?.kind === 'page' ? '' : `#${anchor(id)}`}` : null);

function escapeMd(s) {
  return s.replace(/([\\`*_[\]<>|])/g, '\\$1');
}

function chord(action) {
  const keys = SHORTCUTS[action];
  if (!keys) return 'its shortcut';
  if (!keys.includes('Mod')) return `<kbd>${keys}</kbd>`;
  const other = keys.replace('Mod', 'Ctrl');
  const mac = keys.replace('Mod+', '⌘').replace('Shift+', '⇧').replace('Alt+', '⌥').replace('Comma', ',').replace('Backslash', '\\');
  return `<kbd>${other}</kbd> (<kbd>${mac}</kbd> on a Mac)`;
}

function runsToMd(runs) {
  return runs
    .map((r) => {
      if (r.t === 'text') return escapeMd(r.s);
      if (r.t === 'strong') return `**${escapeMd(r.s)}**`;
      if (r.t === 'em') return `*${escapeMd(r.s)}*`;
      if (r.t === 'key') return chord(r.action);
      const words = r.s ?? byId.get(r.id)?.title ?? r.id;
      const to = href(r.id);
      return to ? `[${escapeMd(words)}](${to})` : escapeMd(words);
    })
    .join('');
}

function md(rich) {
  return help
    .blocks(rich)
    .map((b) => (b.t === 'p' ? runsToMd(b.runs) : b.items.map((item) => `- ${runsToMd(item)}`).join('\n')))
    .join('\n\n');
}

function icon(name) {
  const d = glyphs[name];
  return d ? `<svg class="guide-icon" width="16" height="16" viewBox="0 -960 960 960" fill="currentColor" aria-hidden="true"><path d="${d}"/></svg>` : '';
}

const html = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** A figure as plain HTML: rows of boxes, arrows between neighbours, and a row of arrows between rows. */
function figure(id) {
  const f = help.figureById(id);
  if (!f) return '';
  const rowOf = new Map();
  f.rows.forEach((row, i) => row.forEach((box) => rowOf.set(box.id, i)));
  const out = ['<figure class="guide-figure">', '<div class="guide-frame">'];
  f.rows.forEach((row, i) => {
    const cells = [];
    row.forEach((box, j) => {
      if (j > 0) {
        const prev = row[j - 1].id;
        const edge = f.edges.find((e) => (e.from === prev && e.to === box.id) || (e.to === prev && e.from === box.id));
        if (edge) cells.push(`<span class="guide-side${edge.dashed ? ' dashed' : ''}">${edge.from === prev ? '→' : '←'}${edge.label ? `<small>${html(edge.label)}</small>` : ''}</span>`);
      }
      cells.push(`<div class="guide-box${box.tone ? ` ${box.tone}` : ''}">${box.icon ? icon(box.icon) : ''}<strong>${html(box.label)}</strong>${box.sub ? `<span>${html(box.sub)}</span>` : ''}</div>`);
    });
    out.push(`<div class="guide-row">${cells.join('')}</div>`);
    if (i < f.rows.length - 1) {
      const down = f.edges.filter((e) => (rowOf.get(e.from) === i && rowOf.get(e.to) === i + 1) || (rowOf.get(e.from) === i + 1 && rowOf.get(e.to) === i));
      if (down.length) {
        const up = down.every((e) => rowOf.get(e.from) === i + 1);
        const labels = [...new Set(down.map((e) => e.label).filter(Boolean))];
        out.push(`<div class="guide-down${down.every((e) => e.dashed) ? ' dashed' : ''}">${up ? '↑' : '↓'}${labels.length ? `<small>${html(labels.join(', '))}</small>` : ''}</div>`);
      }
    }
  });
  out.push('</div>', `<figcaption>${html(f.caption)}</figcaption>`, '</figure>');
  return out.join('\n');
}

const SHELL_NAMES = { desktop: 'the desktop app', extension: 'the browser extension', android: 'Android' };
function where(t) {
  if (!t.shells) return '';
  return `*Only in ${t.shells.map((s) => SHELL_NAMES[s]).join(' and ')}.*`;
}

/** One cell of a Markdown table: no line breaks, and no bar that would end the cell. */
const cell = (rich) => md(rich).replace(/\n\n/g, ' ').replace(/\n/g, ' ');

function choices(effects) {
  return ['| Choice | What it does |', '| --- | --- |', ...effects.map((e) => `| ${escapeMd(e.label)} | ${cell(e.text)} |`)].join('\n');
}

/**
 * A topic as one section of a page. Its parts get small headings, below what the page's own table
 * of contents lists, and the phone's differences follow in a part of their own.
 */
function section(t, level = 2) {
  const h = '#'.repeat(level);
  const sub = '#'.repeat(Math.max(level + 2, 4));
  const parts = [`<a id="${anchor(t.id)}"></a>`, '', `${h} ${escapeMd(t.title)}`, ''];
  const only = where(t);
  if (only) parts.push(only, '');
  parts.push(md(t.what), '');
  if (t.figure) parts.push(figure(t.figure), '');
  if (t.why) parts.push(`${sub} Why it is there`, '', md(t.why), '');
  if (t.how) parts.push(`${sub} How it works`, '', md(t.how), '');
  if (t.when) parts.push(`${sub} When to use it`, '', md(t.when), '');
  if (t.effects?.length) parts.push(`${sub} What each choice does`, '', choices(t.effects), '');
  if (t.preview) parts.push('*The guide in the app shows this live, with your own settings.*', '');
  if (t.caveats) parts.push(`${sub} Limits`, '', md(t.caveats), '');
  const android = t.on?.android;
  if (android && (!t.shells || t.shells.includes('android')) && (android.title || android.what || android.how || android.effects || android.caveats)) {
    const lines = [];
    if (android.title && android.title !== t.title) lines.push(`On the phone it is called ${escapeMd(android.title)}.`);
    if (android.what) lines.push(md(android.what));
    if (android.how) lines.push(md(android.how));
    if (android.effects) lines.push(choices(android.effects));
    if (android.caveats) lines.push(md(android.caveats));
    parts.push(`${sub} On Android`, '', lines.join('\n\n'), '');
  }
  const titles = new Set([t.title]);
  const related = (t.related ?? []).filter((id) => href(id) && !titles.has(byId.get(id).title) && titles.add(byId.get(id).title));
  if (related.length) parts.push(`See also ${related.map((id) => `[${escapeMd(byId.get(id).title)}](${href(id)})`).join(', ')}.`, '');
  return parts.join('\n');
}

function page(path, title, description, order, body) {
  const front = ['---', `title: ${JSON.stringify(title)}`, `description: ${JSON.stringify(description)}`, 'sidebar:', `  order: ${order}`, '---', '', HEADER, ''];
  write(join(OUT, path), `${front.join('\n')}${body.trim()}\n`);
}

const plainOf = (t) => help.plain(t.what, (id) => byId.get(id)?.title);

rmSync(OUT, { recursive: true, force: true });

page(
  'index.md',
  'The guide',
  'What every screen, setting and feature in WM Pass does, the same guide the app shows when you press ? or F1.',
  0,
  [
    'This is the guide built into WM Pass. In the app, the **?** beside a setting opens its part of it, and the Help menu or F1 explains the screen you are on. Settings, Guide lists all of it, with tours that point at each part of the window.',
    '',
    '- [Screens](/guide/screens/): the parts of each screen and what you can do there.',
    '- [How WM Pass works](/guide/how-it-works/): the ideas behind the vault, locking, backups, sync and the rest.',
    '- [Tours](/guide/tours/): the step-by-step tours the app can run for you.',
    '- Settings, page by page, in the sidebar under Guide.',
  ].join('\n'),
);

const screens = TOPICS.filter((t) => t.kind === 'screen');
page('screens.md', 'Screens', 'The parts of each screen in WM Pass and what you can do there.', 1, screens.map((t) => section(t)).join('\n'));

const ideas = TOPICS.filter((t) => (t.kind === 'feature' || t.kind === 'concept') && !t.page);
page('how-it-works.md', 'How WM Pass works', 'The ideas behind the vault, locking, backups, sync, sharing and the network features.', 2, ideas.map((t) => section(t)).join('\n'));

const tourLines = [];
for (const tour of help.TOURS) {
  tourLines.push(`## ${escapeMd(tour.title)}`, '');
  if (tour.shells) tourLines.push(`*Only in ${tour.shells.map((s) => SHELL_NAMES[s]).join(' and ')}.*`, '');
  if (tour.width) tourLines.push(`*For a ${tour.width} window.*`, '');
  if (tour.intro) tourLines.push(md(tour.intro), '');
  tour.steps.forEach((s, i) => tourLines.push(`${i + 1}. ${escapeMd(s.title)}. ${md(s.body).replace(/\n\n/g, ' ')}`));
  tourLines.push('');
}
page('tours.md', 'Tours', 'The step-by-step tours WM Pass can run, pointing at each part of the window in turn.', 3, `In the app, start a tour from Settings, Guide, from **Show me** on a page of the guide, or from the Help menu. Each step points at one part of the window; Escape ends the tour.\n\n${tourLines.join('\n')}`);

let order = 10;
const pageIds = settingsPages.map((p) => p.id);
for (const group of GROUPS) {
  const pages = settingsPages.filter((p) => p.group === group);
  for (const info of pages) {
    const top = byId.get(`page.${info.id}`);
    const rows = TOPICS.filter((t) => t.page === info.id && t.kind !== 'page' && t.kind !== 'screen' && !(t.kind === 'feature' && !t.page));
    if (!top && rows.length === 0) continue;
    const title = top?.title ?? PAGES.find((p) => p.id === info.id)?.title ?? info.id;
    const intro = top ? section({ ...top, title: 'About this page' }) : '';
    const body = [intro, ...rows.map((t) => section(t))].join('\n');
    const path = [...ancestors(info.id).map((p) => p.title), title].reduce((all, t) => `${all}, ${t}`, 'Settings');
    page(`settings/${info.id}.md`, title, top ? plainOf(top) : `${path}.`, order++, `Found under ${path}.\n\n${body}`);
  }
}

console.log(`Wrote data/help/help.json and ${pageIds.length} settings pages plus 4 guide pages from ${TOPICS.length} topics.`);
